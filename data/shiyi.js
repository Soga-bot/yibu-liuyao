// ---------- 按文王序对齐生成索引 ----------
const build = raw => {
  const m = {}
  for (const r of raw) {
    const g = GUA_LIST.find(x => x.name === r.n)
    if (!g) throw new Error('shiyi.js 锚点无此卦：' + r.n)
    m[g.key] = r.t
  }
  return m
}
