// tools/gen-baihua-template.mjs — 生成「待填充-白话翻译.txt」与「待校对-彖传小象.txt」
// 用法：node tools/gen-baihua-template.mjs
// 白话填充完成后：把内容按 data/baihua.js 的格式并入（或交给我来转）。
import { writeFileSync } from 'node:fs'
import { GUA_LIST } from '../data/gua.js'
import { BAIHUA } from '../data/baihua.js'

const done = new Set(Object.keys(BAIHUA))   // 已完成的试点卦（跳过）

// ---------- 1. 白话待填充 ----------
let t = `待填充：卦辞 / 爻辞白话翻译（共 ${GUA_LIST.filter(g => !done.has(g.key)).length} 卦）
====================================================================

【怎么填】
1. 每卦在「白话＞」下一行填 1~2 句白话；不用抄题，只填译文。
2. 风格参照 data/baihua.js 已完成的试点 8 卦（乾坤屯蒙需讼师比）。
3. 三条规范（审核红线，务必遵守）：
   ① 只译字面与传统注疏共识，不作吉凶断言、不用预测口吻；
     「吉祥/凶险」等词只在与原文吉凶语对应时出现，不加发挥。
   ② 生僻意象先直译，再点一句传统理解，用「传统认为/古人以此喻」引出。
   ③ 不杜撰：拿不准的典故宁可不展开，写直译即可。
4. 填多少算多少，可分批发我，我来转成 data/baihua.js 并接进页面。

====================================================================
`
for (const g of GUA_LIST) {
  if (done.has(g.key)) continue
  t += `\n【第${String(g.seq).padStart(2, '0')}卦 · ${g.name}】（${g.waiXiang}${g.neiXiang}${g.name} · ${g.gong}宫）\n`
  t += `卦辞：${g.name}：${g.guaci}\n白话＞\n（在此填写）\n`
  for (const y of g.yaoci) {
    t += `\n${y.ti}：${y.ci}\n白话＞\n（在此填写）\n`
  }
  t += `\n------------------------------------\n`
}
writeFileSync('docs/待填充-白话翻译.txt', t, 'utf8')

// ---------- 2. 彖传/小象校对清单 ----------
let c = `待校对：data/zhuan.js（彖传 64 + 小象传 64 + 用九用六小象）
====================================================================

【背景】彖传、小象传由我按通行本录入（data/zhuan.js），已用卦名锚点
校验过 64 卦键位无错位，但文字是凭记忆写的，可能存在个别错字、
漏字或多字，需要对照权威文本校对。

【对着什么校】
推荐任一：中国哲学书电子化计划（ctext.org）周易篇 / 十三经注疏本
《周易正义》/ 上海古籍《周易译注》。

【建议抽查法】（比全查省力，覆盖足够）
先抽 8~10 卦：乾、坤、屯、颐、坎、离、咸、恒、睽、既济。
抽查无误即可认为整体可信；查出错字越多，越建议扩查。

【怎么记错】直接在本文件末尾「纠错记录」按格式记，我来改 zhuan.js：
  卦名｜彖/小象第几条｜现文｜应为
例：屯｜小象第3条｜即鹿无虚｜即鹿无虞

【已核对】（校完打 x）
`
for (const g of GUA_LIST) c += `□ ${String(g.seq).padStart(2, '0')} ${g.name}\n`
c += `
====================================================================
纠错记录（格式：卦名｜彖/小象第几条｜现文｜应为）
（无）
`
writeFileSync('docs/待校对-彖传小象.txt', c, 'utf8')

console.log('已生成：docs/待填充-白话翻译.txt、docs/待校对-彖传小象.txt')
